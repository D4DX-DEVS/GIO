// Image file storage for the website. The only code that knows where image
// files live; the rest of the app calls put / get / remove with a key such as
// "<sha256>.jpg".
//
// ASSET_STORAGE selects the backend:
//   gridfs - files in this app's MongoDB (GridFS bucket "siteassets"). Survives
//            redeploys and is included in every mongodump of the database.
//   local  - files in ASSET_STORAGE_DIR on the server's disk. Only suitable
//            when that disk is persistent and backed up.
// Production must set ASSET_STORAGE explicitly (see config/env.js) once the
// hosting is confirmed.
const fs = require('fs/promises');
const path = require('path');
const mongoose = require('mongoose');
const { env } = require('../config/env');

const KEY_RE = /^[a-f0-9]{64}\.(jpg|png)$/;

function checkKey(key) {
  // Keys are generated by the server; this also rules out path traversal.
  if (!KEY_RE.test(key)) throw new Error(`Invalid asset key: ${key}`);
}

const gridfs = {
  bucket() {
    return new mongoose.mongo.GridFSBucket(mongoose.connection.db, { bucketName: 'siteassets' });
  },
  async exists(key) {
    return Boolean(await mongoose.connection.db.collection('siteassets.files').findOne({ filename: key }, { projection: { _id: 1 } }));
  },
  async put(key, buffer, mime) {
    if (await this.exists(key)) return; // content-addressed: same key, same bytes
    await new Promise((resolve, reject) => {
      const stream = this.bucket().openUploadStream(key, { metadata: { contentType: mime } });
      stream.once('finish', resolve).once('error', reject);
      stream.end(buffer);
    });
  },
  async get(key) {
    if (!(await this.exists(key))) return null;
    const chunks = [];
    for await (const chunk of this.bucket().openDownloadStreamByName(key)) chunks.push(chunk);
    return Buffer.concat(chunks);
  },
  async remove(key) {
    const files = await mongoose.connection.db.collection('siteassets.files').find({ filename: key }, { projection: { _id: 1 } }).toArray();
    for (const f of files) await this.bucket().delete(f._id);
  },
  async list() {
    return (await mongoose.connection.db.collection('siteassets.files').find({}, { projection: { filename: 1 } }).toArray()).map((f) => f.filename);
  },
};

const local = {
  file(key) {
    return path.join(env.assets.dir, key);
  },
  async put(key, buffer) {
    await fs.mkdir(env.assets.dir, { recursive: true });
    const target = this.file(key);
    try {
      await fs.access(target);
      return;
    } catch {
      /* not there yet */
    }
    // Write then rename, so a crash never leaves a half-written image.
    const tmp = `${target}.${process.pid}.tmp`;
    await fs.writeFile(tmp, buffer);
    await fs.rename(tmp, target);
  },
  async get(key) {
    try {
      return await fs.readFile(this.file(key));
    } catch (err) {
      if (err.code === 'ENOENT') return null;
      throw err;
    }
  },
  async remove(key) {
    await fs.rm(this.file(key), { force: true });
  },
  async list() {
    try {
      return (await fs.readdir(env.assets.dir)).filter((f) => KEY_RE.test(f));
    } catch (err) {
      if (err.code === 'ENOENT') return [];
      throw err;
    }
  },
};

function backend() {
  return env.assets.storage === 'local' ? local : gridfs;
}

module.exports = {
  put: (key, buffer, mime) => (checkKey(key), backend().put(key, buffer, mime)),
  get: (key) => (checkKey(key), backend().get(key)),
  remove: (key) => (checkKey(key), backend().remove(key)),
  list: () => backend().list(),
  KEY_RE,
};
